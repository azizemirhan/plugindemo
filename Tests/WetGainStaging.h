/**
    Renders the four production trim candidates blind.

    One wet render per source with no trim applied at all; each candidate is
    then that render scaled by its own trim. Since the width stage is linear,
    scaling before or after it is identical, so this is exact rather than
    approximate - and it guarantees that the four candidates share a tank state
    and a sample alignment by construction.

    Writes candidate-A..D per source per mix point in a shuffled order, plus a
    key and a manifest. Returns the number of audio files written, or a negative
    value on failure.
*/
int exportTrimCandidates (const std::string& directory, double sampleRate = 48000.0);

