/*
    PHASE 7 — ensemble energy-decay gate.

    WHAT CHANGED AND WHY
    --------------------
    The corrected constant-Q analyser removed the band-filter artefact but left
    T20 and T30 read from a SINGLE realisation. Independent excitations then
    disagreed by up to 19 %, and calling that "measurement error" would have
    been wrong: different excitations legitimately weight the tank's modes
    differently, and that is a property of the reverb, not of the ruler.

    So the two are separated here. STIMULUS SENSITIVITY is reported as its own
    diagnostic across 32 realisations, and the GATE is applied to an ensemble
    energy decay curve, whose precision is measured by splitting the ensemble in
    half rather than by looking at how far apart single seeds land.

    The thresholds are untouched: |T20-T30| <= 5 %, R^2 >= 0.995. Only the
    estimator is better defined.
*/

